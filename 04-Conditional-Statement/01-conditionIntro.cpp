/* Conditional Statement */

/*
    Conditional statements allow different sets of instructions
    to be executed depending on the result of a logical test.

    If the condition is true (1), one set of instructions is executed.
    If the condition is false (0), another set of instructions may be executed.

    This process of choosing between different paths is called branching.


    There are different type of branching technique.
    -> if-else
    -> else - if
    -> ternary operator
    -> switch case
*/